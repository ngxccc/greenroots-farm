import "reflect-metadata";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { NestFactory } from "@nestjs/core";
import openapiTS, { astToString } from "openapi-typescript";
import { AppModule } from "../src/app.module";
import { createOpenApiDocument } from "../src/common/config/openapi.config";

/**
 * Generates openapi.json and synchronizes TypeScript type definitions
 * across storefront, backoffice, and API tests offline without requiring
 * live PostgreSQL or Redis connections.
 */
async function generate(): Promise<void> {
  const app = await NestFactory.create(AppModule, { logger: false });

  try {
    // Set global prefix to match runtime main.ts
    app.setGlobalPrefix("api/v1");
    const document = createOpenApiDocument(app);
    const jsonContent = JSON.stringify(document, null, 2);

    // 1. Output openapi.json at apps/api/openapi.json
    const currentDir = fileURLToPath(new URL(".", import.meta.url));
    const openApiPath = resolve(currentDir, "../openapi.json");
    writeFileSync(openApiPath, `${jsonContent}\n`, "utf-8");
    // 2. Generate TypeScript AST and serialize to string
    const ast = await openapiTS(document);
    const generatedTypes = astToString(ast);
    const banner = `/**\n * This file was auto-generated by openapi-typescript via \`bun run types:sync\`.\n * Do not modify this file directly.\n */\n\n`;
    const fullContent = `${banner}${generatedTypes}\n`;

    // 3. Write to consumers: Storefront, Backoffice, API test fixtures
    const targets = [
      resolve(currentDir, "../../storefront/src/types/api-schema.d.ts"),
      resolve(currentDir, "../../backoffice/src/types/api-schema.d.ts"),
      resolve(currentDir, "../test/generated/api-schema.d.ts"),
    ];

    for (const target of targets) {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, fullContent, "utf-8");
    }

    console.log(
      `[types:sync] Successfully generated OpenAPI spec and synchronized ${targets.length} type definitions.`,
    );
  } finally {
    await app.close();
  }
}

void generate();
